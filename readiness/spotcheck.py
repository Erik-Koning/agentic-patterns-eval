"""Readiness H5: the human spot-check sheet of generated tasks (readiness/spotcheck.md).

    uv run python readiness/spotcheck.py            # writes readiness/spotcheck.md

Deterministic: the worlds are the ones the code generates for these seeds, and the samples come from fixed-seed
RNGs, so the same code always writes the same file.

- **Part A, the gate** (review before the gate pilot; DECISIONS H5). 20 tasks per gate family, drawn from the exact
  dev worlds the gate's build-dev phase builds: `gate.build.dev` world counts and `gate.tune` tasks per world from
  config/run_plan.yaml, relational, descriptive exceptions.
  - F7: 10 from F7-10 and 10 from F7-1000, stratified over the exception cases.
  - F3: 10 from F3-5 and 10 from F3-60.
- **Part B, the main study and Study G** (not needed for the gate): 10 F1 tasks, 10 F2 tasks and one short F8
  session.

For every task the sheet shows the prompt, the gold, the gold facts' text, the tool data the task depends on, and
a checklist.
"""

import json
import random
from collections import Counter
from pathlib import Path

from ape.budget import load_plan
from ape.worlds import gen_f8, gen_registry
from ape.worlds.generate import make_world
from ape.worlds.spec import TaskItem, World

OUT = Path(__file__).with_name("spotcheck.md")
F7_CASES = (("exception_applies", 4), ("exception_not_applicable", 3), ("no_exception", 3))  # 10 per F7 cell
PER_CELL = 10
F1_SAMPLE = (("2", 4), ("8", 4), ("32", 2))
F2_SAMPLE = (("2", 4), ("5", 3), ("10", 3))
REGISTRY_TASKS = 12  # tasks per F1/F2 world (as the gate's dev worlds)
F8_N = 12
F8_STATE_AT = 6
CHECKLIST = [
    "- [ ] **Gold correct:** it follows from the gold facts and the tool data alone.",
    "- [ ] **Prompt unambiguous:** one reading, and it names everything the task needs.",
    "- [ ] **Evidence sufficient:** the gold facts are enough; nothing else is needed.",
    "- [ ] **Answer format clear:** the answer tool and what goes in it are clear.",
    "- Verdict: [ ] OK  [ ] ISSUE: ______________________________",
]

HEADER = """# Task spot-check (H5)

Generated by `uv run python readiness/spotcheck.py`. The same code always writes the same file, so re-run it
after any generator change and review the diff.

## How to review

- **What to check.** Every task has four checks:
  - The **gold** follows from the gold facts and the tool data shown.
  - The **prompt** has one reading.
  - The **evidence** is sufficient.
  - The **answer format** is clear.
  Tick each, then mark the task OK or ISSUE with a one-line note.
- **What "gold correct" means:**
  - **F7:** find the policy whose domain, region and amount band match. If an exception to it matches the customer's
    tier, the exception's outcome replaces the policy's; otherwise the policy's outcome stands.
  - **F3:** the gold calls are exactly the procedure's steps for the order's region, with the procedure's constants
    and the order ID, then `finish`.
  - **F1:** each supplier's rating follows its segment's rule applied to that quarter's two metrics.
  - **F2:** each hop follows the current supplier's escalation code to the supplier the directory routes it to.
- **A defect** is any ISSUE: a wrong gold, an ambiguous prompt, missing evidence, or an unclear format.
  - Write the task ID and the problem in the note.
  - The generator is fixed and the dev worlds rebuilt (`run_gate build-dev` re-runs on the changed worlds).
  - The fix is recorded in DECISIONS.md.
- **Gating.**
  - An ISSUE in Part A blocks the gate pilot until it is fixed.
  - An ISSUE in Part B blocks only its own study's pilot.
- **Time.**
  - Part A: 40 tasks at about a minute each, **30–45 minutes**.
  - Part B: **20–30 minutes**. F1-32 tables take the longest.
"""


def _plan_sizes() -> tuple[dict[str, int], int]:
    plan = load_plan()
    return dict(plan.cell("gate.build.dev").spec["worlds"]), int(plan.cell("gate.tune").spec["tasks_per_world"])


def _gate_worlds(cell: str, count: int, n_tasks: int) -> list[World]:
    family, level = cell.split("-", 1)
    return [make_world(family, level, "dev", i, n_tasks, True, "descriptive") for i in range(count)]


def _facts(world: World, task: TaskItem) -> list[str]:
    return ["**Gold facts:**", *[f"- `{f}`: {world.facts[f].text}" for f in task.gold_fact_ids], ""]


def _sample_f7(rng: random.Random, tasks: list[TaskItem]) -> list[TaskItem]:
    """PER_CELL tasks stratified over the exception cases (F7_CASES quotas; a short case is filled from the others)."""
    by_case: dict[str, list[TaskItem]] = {}
    for t in tasks:
        by_case.setdefault(t.tags.get("case"), []).append(t)
    picked: list[TaskItem] = []
    for case, quota in F7_CASES:
        pool = by_case.get(case, [])
        picked += rng.sample(pool, min(quota, len(pool)))
    rest = [t for t in tasks if t not in picked]
    picked += rng.sample(rest, min(PER_CELL - len(picked), len(rest)))
    return sorted(picked, key=lambda t: t.id)


def _f7_block(world: World, t: TaskItem, n: str) -> list[str]:
    cid = t.tags["customer_id"]
    cust = t.setup["customers"][cid]
    g = t.gold
    approver = f", approver {g['approver']}" if g["approver"] != "none" else ""
    return [
        f"##### {n} · `{t.id}` · {t.tags['case'].replace('_', ' ')}",
        "",
        f"**Prompt:** {t.prompt}",
        "",
        f"**Tool data:** `lookup_customer(\"{cid}\")` returns region **{cust['region']}**, tier **{cust['tier']}**.",
        "",
        f"**Gold** (`submit_decision`): **{g['action']}**{approver}, deadline {g['deadline_days']} days, document {g['document']}.",
        "",
        f"**Generator's match:** policy {t.tags['policy']} ({t.tags['domain']}, ${t.tags['amount']:,}); case {t.tags['case']}.",
        "",
        *_facts(world, t),
        *CHECKLIST,
        "",
    ]


def _f3_block(world: World, t: TaskItem, n: str) -> list[str]:
    orders = t.setup["orders"]
    data = "; ".join(f"`order_lookup(\"{o}\")` returns region **{v['region']}**, status {v['status']}" for o, v in orders.items())
    calls = [f"{i}. `{c['tool']}({', '.join(f'{k}={v}' for k, v in c['args'].items())})`" for i, c in enumerate(t.gold["calls"], 1)]
    return [
        f"##### {n} · `{t.id}` · {t.tags['procedure']}",
        "",
        f"**Prompt:** {t.prompt}",
        "",
        f"**Tool data:** {data}.",
        "",
        "**Gold calls** (exactly these mutating calls, any order, then `finish`):",
        *calls,
        "",
        *_facts(world, t),
        *CHECKLIST,
        "",
    ]


def part_a() -> list[str]:
    worlds_per_cell, n_tasks = _plan_sizes()
    lines = [
        "## Part A: gate families (review before the gate pilot)",
        "",
        f"Drawn from the gate's dev worlds: {', '.join(f'{c} ×{n}' for c, n in worlds_per_cell.items())} worlds, {n_tasks} tasks each "
        "(run_plan.yaml `gate.build.dev`, `gate.tune`), relational, descriptive exceptions.",
        "",
    ]
    for family, cells in (("F7", ("F7-10", "F7-1000")), ("F3", ("F3-5", "F3-60"))):
        lines += [f"### {family}", ""]
        for cell in cells:
            worlds = _gate_worlds(cell, worlds_per_cell[cell], n_tasks)
            tasks = [t for w in worlds for t in w.tasks]
            rng = random.Random(f"H5|{cell}")
            picked = _sample_f7(rng, tasks) if family == "F7" else sorted(rng.sample(tasks, min(PER_CELL, len(tasks))), key=lambda t: t.id)
            by_id = {w.id: w for w in worlds}
            counts = Counter(t.tags.get("case") for t in picked)
            mix = "; " + ", ".join(f"{counts[c]} {c.replace('_', ' ')}" for c, _ in F7_CASES if counts[c]) if family == "F7" else ""
            lines += [f"#### {cell} ({len(picked)} tasks from {', '.join(f'`{w.id}`' for w in worlds)}{mix})", ""]
            for i, t in enumerate(picked, 1):
                block = _f7_block if family == "F7" else _f3_block
                lines += block(by_id[t.world_id], t, f"A-{cell}-{i:02d}")
    return lines


# --- Part B --------------------------------------------------------------------------------------------


def _f1_block(world: World, t: TaskItem, n: str) -> list[str]:
    q, suppliers = t.tags["quarter"], world.entities["suppliers"]
    rules = {r["segment"]: r for r in world.entities["rules"]}
    rows = []
    for sub in t.tags["subtasks"]:
        rec = suppliers[sub["id"]]
        rule = rules[rec["segment"]]
        metrics = ", ".join(f"{m} {rec['scorecard'][q][m]}" for m in (rule["m1"], rule["m2"]))
        rows.append(f"| {sub['id']} | {rec['segment']} | {metrics} | **{sub['gold']}** |")
    return [
        f"#### {n} · `{t.id}` · N = {t.tags['n']}, {q}",
        "",
        f"**Prompt:** {t.prompt}",
        "",
        f"**Tool data and gold** (`lookup_supplier` records: segment and the rule's two metrics for {q}; gold via `submit_ratings`):",
        "",
        "| Supplier | Segment | Rule metrics | Gold rating |",
        "|---|---|---|---|",
        *rows,
        "",
        *_facts(world, t),
        *CHECKLIST,
        "",
    ]


def _f2_block(world: World, t: TaskItem, n: str) -> list[str]:
    suppliers, routes = world.entities["suppliers"], world.entities["routes"]
    rows, cur = [], t.tags["start"]
    for hop, code in enumerate(t.tags["codes"], 1):
        nxt = routes[code]
        rows.append(f"| {hop} | {cur} | `{suppliers[cur]['escalation_code']}` | {nxt} |")
        cur = nxt
    fault = t.tags["fault"]
    return [
        f"#### {n} · `{t.id}` · k = {t.tags['k']}",
        "",
        f"**Prompt:** {t.prompt}",
        "",
        "**Tool data and directory** (the escalation code on the current supplier's record, then the directory's route):",
        "",
        "| Hop | From | Code on record | To |",
        "|---|---|---|---|",
        *rows,
        "",
        f"**Gold** (`submit_chain`): final **{t.gold['final']}**, chain {' → '.join(t.gold['chain'])}.",
        "",
        f"*Study D fault (off unless enabled): hop {fault['hop']}'s first lookup of {fault['key']} reports {fault['value']} instead of {fault['true_value']}.*",
        "",
        *_facts(world, t),
        *CHECKLIST,
        "",
    ]


def _withdrawn(memo: dict) -> str:
    return f"withdrawn at case {memo['withdrawn_at']}" if memo["withdrawn_at"] else "never withdrawn"


def _f8_section() -> list[str]:
    w = make_world("F8", str(F8_N), "dev", 0, 0)
    s = gen_f8.session(w)
    lines = [
        f"### F8: one short session (`{w.id}`, N = {F8_N}, Study G)",
        "",
        "Per-case decisions use the F7/F3 rules reviewed in Part A. Here, review the session structure: memos, quota, "
        f"follow-ups, the state after {F8_STATE_AT} cases and the report.",
        "",
        f"**Shift rules:** quota of {s['quota']} approvals per customer; knobs {json.dumps(s['knobs'], sort_keys=True)}.",
        "",
        "**Memos:**",
        *[f"- **{m['id']}**, announced at case {m['position']}, {_withdrawn(m)}: {m['text']}" for m in s["memos"]],
        "",
        "| # | Case | Kind | Depends on | Customer (region, tier) | Gold |",
        "|---|---|---|---|---|---|",
    ]
    for t in w.tasks:
        tg = t.tags
        dep = ", ".join(tg["dependency_kinds"]) + (f" ({tg['original']})" if tg.get("original") else "") if tg["dependency_kinds"] else "–"
        cust = s["customers"].get(tg.get("customer_id", ""), {})
        who = f"{tg['customer_id']} ({cust.get('region')}, {cust.get('tier')})" if "customer_id" in tg else f"order {tg.get('order_id')}"
        gold = "resolved: " + ", ".join(c["tool"] for c in t.gold["calls"]) if tg["kind"] == "ticket" else (
            f"{t.gold['action']}" + (f" ({t.gold['approver']})" if t.gold["approver"] != "none" else "") + f", {t.gold['deadline_days']} d, {t.gold['document']}"
        )
        flags = (" · awaits follow-up" if tg["awaiting"] else "") + (" · quota" if tg["quota_triggered"] else "")
        lines.append(f"| {tg['position']} | {tg['case_id']} | {tg['kind']}{flags} | {dep} | {who} | {gold} |")
    picks = [w.tasks[0]] + [t for t in w.tasks if t.tags["kind"] == "followup"][:1] + [t for t in w.tasks if t.prompt.startswith("MEMO")][:1]
    shown = sorted({t.tags["position"]: t for t in picks}.values(), key=lambda t: t.tags["position"])
    lines += ["", f"**{len(shown)} messages as the agent sees them** (the first case, a follow-up and a memo announcement):", ""]
    for t in shown:
        first, *more = t.prompt.split("\n")
        lines += [f"- Case {t.tags['position']}: {first}", *[f"  <br>{line}" for line in more]]
    lines += [
        "",
        f"**State after {F8_STATE_AT} cases** (`state_at`, what the probes are scored against): `{json.dumps(gen_f8.state_at(w, F8_STATE_AT), sort_keys=True)}`",
        "",
        f"**Report gold:** `{json.dumps(gen_f8.report_gold(w), sort_keys=True)}`",
        "",
        "- [ ] **Memos:** each memo changes exactly the cases it should while it is in force.",
        "- [ ] **Quota:** a customer's third approve-able request is escalated to the team lead.",
        "- [ ] **Follow-ups:** each re-decides its original under the memos in force at the follow-up.",
        "- [ ] **State and report:** both match the table.",
        "- Verdict: [ ] OK  [ ] ISSUE: ______________________________",
        "",
    ]
    return lines


def part_b() -> list[str]:
    lines = ["## Part B: main study and Study G (not needed for the gate)", ""]
    for family, sample, block in (("F1", F1_SAMPLE, _f1_block), ("F2", F2_SAMPLE, _f2_block)):
        lines += [f"### {family}", ""]
        for level, k in sample:
            w = make_world(family, level, "dev", 0, REGISTRY_TASKS)
            rng = random.Random(f"H5|{family}-{level}")
            for i, t in enumerate(sorted(rng.sample(w.tasks, k), key=lambda t: t.id), 1):
                assert gen_registry.solve(w, t) == t.gold, t.id  # the sheet never shows a gold the solver disagrees with
                lines += block(w, t, f"B-{family}-{level}-{i:02d}")
    return lines + _f8_section()


def render() -> str:
    return "\n".join([HEADER, *part_a(), *part_b()]).rstrip() + "\n"


def main() -> None:
    OUT.write_text(render())
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
